/**
 * The pedal's analog supply (h7 pedal pages plan, Task 6; inventory section 1.3 B5; CR-PEDAL-BLOCKS
 * `ldo_vmid`): 5V_A from VIN_A, the R_5VA link to the codec's VCC net, and VMID.
 *
 * - U_LDO, TPS7A4901DGNR, on VIN_A (power.md:474; D3). Pin-level as PWR-08 states it
 *   (schematic-checklist.md:129): IN (8) and EN (5) on VIN_A, "EN tied to IN"; OUT (1) = 5V_A; FB (2);
 *   NR/SS (6); pin 7 DNC "connected to nothing, not even GND", a no-connect; NC (3) "open or GND", left
 *   open (CR-PEDAL-POWER-READINGS); GND (4) and the
 *   PowerPAD (9 on the project symbol, CR-PEDAL-SYMBOL-TPS7A4901) on GND.
 * - Feedback 32.4 kOhm (5V_A to FB) over 10.0 kOhm (FB to GND): 5.024 V (power.md:474; R_LDOT, R_LDOB,
 *   PWR-08). CIN 10 uF 50 V on VIN_A (C_LIN, parts.md:57); COUT 10 uF (C_LOUT, parts.md:83); CNR/SS and
 *   CFF 10 nF (parts.md:84). Where those two go is the data sheet's, which the documents do not write
 *   (CR-PEDAL-POWER-DATASHEET-ENDS quotes it):
 *   TI SBVS121E (rev. May 2015), https://www.ti.com/lit/ds/symlink/tps7a49.pdf, fetched 2026-11-13, p. 4
 *   Pin Functions, NR/SS: "Connecting an external capacitor to this pin bypasses noise generated by the
 *   internal band gap" (so NR/SS to GND); p. 6 Electrical Characteristics note 4, "CFF refers to a
 *   feed-forward capacitor connected to the FB and OUT pins".
 * - R_5VA, an 0805 0 ohm, fitted, in series between the LDO output and the codec's VCC decoupling
 *   (power.md:489; schematic-checklist.md:138, PWR-15): 5V_A to 5V_A_CODEC. 5V_A_CODEC's other members
 *   are in `codec_sup` and `codec` (Task 8), so it is an awaiting net of the board until then.
 * - VMID: 2 x 100 kOhm 0.1 % 25 ppm/C from VIN_A to GND with 10 uF 50 V X7R at the node
 *   (schematic-checklist.md:130, PWR-09; analog.md:148, CL31B106KBHNNNE). The node is VMID, the
 *   documents' "VMID = VIN_A / 2" (power.md:488).
 * - U_VMID, one whole OPA1688 dual: A drives VMID_L and B VMID_R, each a unity-gain follower (output on
 *   its inverting input) with no output capacitor, each non-inverting input fed from VMID through
 *   10.0 kOhm 1 % (schematic-checklist.md:131, PWR-10; analog.md:149). V+ on VIN_A (power.md:33), V- on
 *   GND, V+ decoupled by 100 nF + 10 uF 50 V to GND (schematic-checklist.md:132, PWR-11; the 10 uF is
 *   parts.md:57's op-amp decoupling part).
 * - Test pad on 5V_A (CR-PEDAL-TEST-PADS).
 *
 * MPNs are parts.md's where it gives one; the feedback, divider, follower-input, 0 ohm and 100 nF
 * parts have none there (PWR-08, PWR-09 and PWR-15 name only what v1 contained), and a schematic needs
 * none (G245).
 */
import { NC } from "../../../lib/model/index.ts"
import type { Network, PartSpec } from "../../../lib/model/index.ts"
import { CAPACITOR, RESISTOR, TEST_POINT } from "../parts.ts"
import { C10U_50V, OPA1688, TPS7A4901 } from "../pedal-parts.ts"
import { block, capacitor, dualOpamp, part, resistor } from "./build.ts"

const withMpn = (base: PartSpec, mpn: string): PartSpec => ({ ...base, mpn })

const VIN_A = "VIN_A"
const V5A = "5V_A"
const V5A_CODEC = "5V_A_CODEC"
const VMID_L = "VMID_L"
const VMID_R = "VMID_R"
const GND = "GND"
const FB = "LDO_FB"
const NR = "LDO_NR"
const VMID = "VMID"
const IN_L = "VMID_IN_L"
const IN_R = "VMID_IN_R"

const LDO = "power.md:474 (U_LDO; D3)"
const PWR08 = "schematic-checklist.md:129 (PWR-08)"
const SBVS121E = "CR-PEDAL-POWER-DATASHEET-ENDS: TI SBVS121E (rev. May 2015)"
const DIV = "schematic-checklist.md:130 (PWR-09, 2 x 100 kOhm 0.1 % 25 ppm/C from VIN_A to GND); power.md:488"
const FOLLOW = "schematic-checklist.md:131 (PWR-10, each input fed from the divider through 10.0 kOhm 1 %)"
const DECOUPLE = "schematic-checklist.md:132 (PWR-11, V+ with 100 nF + 10 uF 50 V to GND)"
const C10N = withMpn(CAPACITOR, "CL21B103KBANNNC")

export function ldoVmidBlock(): Network {
  return block([
    part("u_ldo", "ic", { "1": V5A, "2": FB, "3": NC, "4": GND, "5": VIN_A, "6": NR, "7": NC, "8": VIN_A, "9": GND }, TPS7A4901,
      `${LDO}; ${PWR08}: IN (8), EN (5) tied to IN, OUT (1) = 5V_A, pin 7 DNC no-connect, NC (3) open (CR-PEDAL-POWER-READINGS), GND (4) and PowerPAD; parts.md:86`),
    resistor("r_ldot", "32.4k", V5A, FB, RESISTOR, `${LDO}: feedback 32.4 kOhm over 10.0 kOhm; ${PWR08} (R_LDOT)`),
    resistor("r_ldob", "10.0k", FB, GND, RESISTOR, `${LDO}: feedback 32.4 kOhm over 10.0 kOhm; ${PWR08} (R_LDOB)`),
    capacitor("c_lin", "10u", VIN_A, GND, C10U_50V, `${LDO}: CIN 10 uF 50 V; parts.md:57 (C_LIN)`),
    capacitor("c_lout", "10u", V5A, GND, withMpn(CAPACITOR, "CL31B106KOHNNNE"), `${LDO}: COUT 10 uF; parts.md:83 (C_LOUT)`),
    capacitor("c_nr", "10n", NR, GND, C10N, `${LDO}: CNR/SS 10 nF; parts.md:84 (C_NR); to GND: ${SBVS121E} p. 4 Pin Functions, NR/SS`),
    capacitor("c_ff", "10n", V5A, FB, C10N, `${LDO}: CFF 10 nF; parts.md:84 (C_FF); FB to OUT: ${SBVS121E} p. 6 note 4`),
    resistor("r_5va", "0", V5A, V5A_CODEC, RESISTOR,
      "power.md:489 (R_5VA, 0805 0 ohm fitted between the LDO output and the codec VCC decoupling; 5V_A_CODEC); schematic-checklist.md:138 (PWR-15)"),
    resistor("r_vmid_top", "100k", VIN_A, VMID, RESISTOR, DIV),
    resistor("r_vmid_bottom", "100k", VMID, GND, RESISTOR, DIV),
    capacitor("c_vmid", "10u", VMID, GND, C10U_50V, "analog.md:148 (10 uF 50 V X7R CL31B106KBHNNNE at the node); schematic-checklist.md:130"),
    resistor("r_vmid_in_l", "10.0k", VMID, IN_L, RESISTOR, `${FOLLOW}; analog.md:149`),
    resistor("r_vmid_in_r", "10.0k", VMID, IN_R, RESISTOR, `${FOLLOW}; analog.md:149`),
    dualOpamp("u_vmid", { "in+": IN_L, "in-": VMID_L, out: VMID_L }, { "in+": IN_R, "in-": VMID_R, out: VMID_R },
      { "v+": VIN_A, "v-": GND }, OPA1688,
      "schematic-checklist.md:131 (PWR-10, channel A to VMID_L and B to VMID_R, unity-gain followers); power.md:33 (U_VMID on VIN_A); schematic-checklist.md:132 (V- on GND); parts.md:105"),
    capacitor("c_vmid_hf", "100n", VIN_A, GND, CAPACITOR, DECOUPLE),
    capacitor("c_vmid_bulk", "10u", VIN_A, GND, C10U_50V, `${DECOUPLE}; parts.md:57 (op-amp decoupling)`),
    part("tp_5v_a", "connector", { "1": V5A }, TEST_POINT, "CR-PEDAL-TEST-PADS (5V_A)"),
  ], [VIN_A, V5A, V5A_CODEC, VMID_L, VMID_R, GND])
}
