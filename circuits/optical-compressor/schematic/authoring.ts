/**
 * TWO RAILS, AND THE TWO NETS THAT LOOK LIKE RAILS AND ARE NOT.
 *
 * `GND` and `+9V_PROTECTED` are rails, and both are forced rather than chosen: the two TL072
 * packages put V- on `GND` and V+ on `+9V_PROTECTED`, those pins are `power_in` in the symbol, and
 * the IR's `pinSemantics` rule refuses a `power_in` pin on a net that is not a declared rail.
 *
 * - **`+9V_RAW` is not a rail.** It is a two-pin net - J_PWR's supply terminal and the 1N5817's
 *   anode - and the whole point of section 8.1's series protection is that it is NOT the rail the
 *   circuit runs on. `../index.ts` says the module's numbers are stated *"against the PROTECTED
 *   rail"*;
 * - **`VBIAS` is not a rail either**, although it reaches ten components. `RailSpec.kind` is
 *   `"ground" | "supply"` and VBIAS is neither: it is a mid-supply bias REFERENCE generated by a
 *   divider and buffered by U2 section B, and spec section 6.1.3 states it as a measured target
 *   rather than a supplied rail. Drawing it with a power glyph would assert that it is fed from
 *   outside the block that makes it. It crosses block boundaries as an ordinary interface port,
 *   which is what it is.
 *
 * `pwrFlag` is null for the reason `circuits/opamp-buffer.schematic.ts` gives.
 */
