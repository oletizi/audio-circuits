#!/usr/bin/env bash
# Replay the h7-module drawing (design change C3) from a fresh `make draw` to every committed
# sheet, in a work directory, checking every sha256 and every generated op-list on the way. Exits
# non-zero on any mismatch.
#
# It grows one block at a time, as each page is repaired (H7 module plan Task 7). Today it drafts
# all twelve pages, checks each draft and its intent against the committed record, and repairs the
# power page and each Task 7b, Task 7c and Task 7d page (repair_block), which is every block; then
# assembles the root (Task 7e) and writes its .kicad_pro.
#
# Fails loudly: the work directory must be new or empty, every command's status is checked through
# pipes (pipefail), each generated op-list must be byte-identical to the committed one, each
# `akcli draw` must report APPLIED (its dry run also exits 0 having written nothing - TOOLING.md
# step 4), and each repaired block sheet must pass hierarchical-labels.ts's post-condition.
#
# usage: bash replay.sh <new-or-empty-work-dir>
set -eu
set -o pipefail
here="$(cd "$(dirname "$0")" && pwd)"
drafted="$(cd "$here/.." && pwd)"
root="$(cd "$here/../../../.." && pwd)"
akcli="$root/draughting/venv-akcli/bin/akcli"
module="$root/circuits/h7-platform/module-board.ts"
board=h7-module

# The drafts make draw writes, one per block, in Network.blocks order.
BLOCKS="mcu decoupling vdda power sdram qspi clock reset_boot swd usb_dfu id_strap interface"
draft_sha() {
  case "$1" in
    mcu) echo f4814efe8202001dd8ecf2cb64c56e3c329ff604ce91f30292b64448fd4282eb ;;
    decoupling) echo 6c9d10a2f9cbeb8219380d3f52f54f23c9a775133e486012934166587d2eefdb ;;
    vdda) echo dd3216347137c8e7b95ee07b03fade7d19382283ce2f95e4bfa52d6d3ed79bdd ;;
    power) echo 1aee153350e07e96d7ecc09a5b25a4ff6c6987016244840a081d716b79df38b4 ;;
    sdram) echo bd560a2406a4ab6d7181202cf0cc59861d7880ff1bddf0592f075e93df04f2f8 ;;
    qspi) echo 1cde054c9d8e9d8cf2e362503d47a140ea39cf69bc709774d2ee9aa4e1a4c788 ;;
    clock) echo 4e6c1565f3b035a5137d2ee2aec5d5c428d6b4a8e4bb3ae2206769dac3a236bb ;;
    reset_boot) echo a68c14b8c7814103c3f5ebb7b24d6016b3c2a125ec5964000031a1b170c9d5e1 ;;
    swd) echo a772b4a70a576bf77c940ac686b81a5d6259b442e5eefda3c840f3cc6d637837 ;;
    usb_dfu) echo 8961061ef5970c5f567bb53c8adcb63d83636187c63391dbc16ad284c83fe791 ;;
    id_strap) echo 4155a90943894fc2dedf9945034ec3d4c3a35f7cde36052c74fb1d9f13ec6ddd ;;
    interface) echo a19804fc684e8b0d33d8fc50b305421b2399378590f109a260f56d9b5c2adaae ;;
    *) fail "no draft sha256 recorded for block $1" ;;
  esac
}
PAGE_POWER=906f454928df01a8c32826a277f041e2a3151fef8ac69a967f14f7abf8b7875f
PAGE_INTERFACE=0cfb3dac4f7a8c8f63c965390c36897a0f21793d865e379070d6d610cd028296
PAGE_CLOCK=83f751b213f71266095f3826df5283bc5ae53208d95f4757f5d53824a83b55b1
PAGE_RESET_BOOT=00407478a4357332aa46164387305ba433dec173796b8d343d3bad86e09bdd24
PAGE_SWD=486923651c80caf44123005ed47fcb5a756c128674a052a4f99727a96b8cfef8
PAGE_USB_DFU=80947ededbb593f37bd87d6e838d232557dfc07c6f6d147ac6257cca5f5a299f
PAGE_ID_STRAP=7649af4311431f60b159a7d6717c26d136ed3311182f3d5330f11a44eba6cf09
PAGE_QSPI=a9578cf6b8bc881ce1cd57d98c862a80241e772c9e7e687195b897e33ca23ea1
PAGE_VDDA=7f066a9ab786252b592d14ffaa8886e934876bcc678666b73c1922f06eee2444
PAGE_SDRAM=0812ab0287bdb8e126f8bd3b2d4a09e54251ee6dc0e62e784d871b9947a48bcf
PAGE_DECOUPLING=8d20ff5196f59330bb77424024d856124808d3d49c5affe89db56f7516c416cb
PAGE_MCU=c3d780a2ec08d385c4fe777c288f851f3c8803754cf995c6cb6f1da49539f981
ROOT_BLANK=134c620e32f4587ab861a8210298ae31533ca041247b3bb183f8e1b13eef25d2
ROOT=3590b959500bd1a3d359915094601450f5437ce071a644dad084aa20e98a99ed
ROOT_PRO=62905f75e8abc6cf0890616b8021b8a31140395b01575e817e372bbd6f09a5a0

fail() {
  echo "replay.sh: FAILED - $1" >&2
  exit 1
}

[ "$#" -eq 1 ] || fail "expected one argument, a new or empty work directory; got $#"
mkdir -p "$1"
work="$(cd "$1" && pwd)"
[ -z "$(ls -A "$work")" ] || fail "$work is not empty; replay into a new or empty directory so nothing from an earlier run is read"
[ -x "$akcli" ] || fail "akcli not found at $akcli"

sha() {
  shasum -a 256 "$1" | cut -d' ' -f1
}

check() {
  got="$(sha "$work/$1")" || fail "could not hash $work/$1"
  [ "$got" = "$3" ] || fail "after $2, $1 is $got, expected $3"
  echo "after $2, $1: $got"
}

same() {
  cmp -s "$work/repair/$1" "$here/$1" || fail "repair/$1 generated by this replay differs from the committed $here/$1"
  echo "generated repair/$1 matches the committed copy"
}

# akcli's stderr goes to a file in the work directory, named in the failure, so a refusal keeps its
# reason (Task 7a review M2: it went to /dev/null).
apply() {
  err="$work/akcli-$(echo "$2" | tr '/' '-').err"
  "$akcli" plan "$work/$1" --ops "$work/repair/$2" 2>"$err.plan" | tail -1 || fail "akcli plan $2 failed; its stderr is in $err.plan"
  log="$("$akcli" draw "$work/$1" --ops "$work/repair/$2" --apply 2>"$err.draw")" || fail "akcli draw $2 --apply failed; its stderr is in $err.draw"
  echo "$log" | tail -1
  echo "$log" | grep -q 'status: APPLIED' || fail "akcli draw $2 did not report APPLIED - nothing was written; its stderr is in $err.draw"
}

# 1. make draw: one draft per block, each intent and each draft checked against the record.
make -C "$root/boards/$board" draw > "$work/make-draw.log" 2>&1 \
  || fail "make -C boards/$board draw failed; see $work/make-draw.log"
# Since Task 7e the board declares a "netlist" (the root's export, tests/fixtures/h7-module.net), so
# make draw runs its per-block partition check against it (tools/draught/draw-partition.ts; a refusal
# stops make draw non-zero, which fails above) and prints no NO INDEPENDENT NETLIST block. The drafts
# are the same bytes either way: each is checked against its recorded sha256 below.
if grep -q '^NO INDEPENDENT NETLIST:' "$work/make-draw.log"; then
  fail "make draw printed a NO INDEPENDENT NETLIST block, so it did not read the board's declared netlist"
fi
mkdir -p "$work/repair"
for b in $BLOCKS; do
  cp "$root/build/draw/$board/$b/$b.kicad_sch" "$work/$b.kicad_sch" || fail "make draw wrote no sheet for block $b"
  cmp -s "$root/build/draw/$board/$b.intent.json" "$here/$b/intent.json" \
    || fail "the intent make draw generated for block $b differs from the committed $b/intent.json - the model has changed since this record"
  # Assigned first, so an unrecorded block stops the replay with draft_sha's own message: inside an
  # argument's $(...) its `fail` exits only the subshell (Task 7a review M3).
  want="$(draft_sha "$b")" || exit 1
  check "$b.kicad_sch" "make draw" "$want"
done
echo "every block's intent matches its committed copy"

# 2. power: place, wire, flag, hierarchical labels, text edits.
b=power
mkdir -p "$work/repair/$b"
python3 "$here/tools/net_strokes.py" "$work/$b.kicad_sch" > "$work/repair/$b/net_strokes.json" || fail "net_strokes.py $b failed"
same "$b/net_strokes.json"
python3 "$here/$b/01-place.py" "$work/$b.kicad_sch" > "$work/repair/$b/01-place.json" || fail "01-place.py $b failed"
same "$b/01-place.json"
apply "$b.kicad_sch" "$b/01-place.json"
python3 "$here/tools/pins.py" "$work/$b.kicad_sch" > "$work/repair/$b/pins.json" || fail "pins.py $b failed"
same "$b/pins.json"
python3 "$here/$b/02-wire.py" "$work/repair/$b/pins.json" "$b.kicad_sch" "$work/repair/$b/02-wire.nets.json" \
  > "$work/repair/$b/02-wire.json" || fail "02-wire.py $b failed"
same "$b/02-wire.json"
same "$b/02-wire.nets.json"
apply "$b.kicad_sch" "$b/02-wire.json"
python3 "$here/$b/03-pwr-flags.py" "$work/repair/$b/pins.json" "$b.kicad_sch" > "$work/repair/$b/03-pwr-flags.json" \
  || fail "03-pwr-flags.py $b failed"
same "$b/03-pwr-flags.json"
apply "$b.kicad_sch" "$b/03-pwr-flags.json"
(cd "$root" && bun tools/draught/hierarchical-labels.ts ops "$module" "$b" "$work/$b.kicad_sch") \
  > "$work/repair/$b/04-hierarchical-labels.json" || fail "hierarchical-labels.ts ops $b failed"
same "$b/04-hierarchical-labels.json"
apply "$b.kicad_sch" "$b/04-hierarchical-labels.json"
(cd "$root" && bun tools/draught/hierarchical-labels.ts check "$module" "$b" "$work/$b.kicad_sch") \
  || fail "block $b fails the hierarchical-label post-condition after its op-list"
python3 "$here/$b/05-text-edits.py" "$work/$b.kicad_sch" "$work/repair/$b/02-wire.nets.json" \
  "$work/repair/$b/net_strokes.json" || fail "05-text-edits.py $b failed"
check "$b.kicad_sch" "01 to 05" "$PAGE_POWER"
cmp -s "$work/$b.kicad_sch" "$drafted/$b.kicad_sch" || fail "the replayed $b.kicad_sch differs from the committed $drafted/$b.kicad_sch"
echo "the replayed $b.kicad_sch is byte-identical to the committed sheet"

# 2b. The blocks repaired in Task 7b, each by the shared tools (tools/page.py) and its own layout.py
#     and 02-wire.py: ports, strokes, place, pins, wire, any private PWR_FLAGs, hierarchical labels,
#     text edits. The ports file is generated first because layout.py may read it.
repair_block() {
  b="$1"
  want="$2"
  mkdir -p "$work/repair/$b"
  (cd "$root" && bun "$here/tools/ports.ts" "$b") > "$work/repair/$b/ports.json" || fail "ports.ts $b failed"
  same "$b/ports.json"
  python3 "$here/tools/net_strokes.py" "$work/$b.kicad_sch" > "$work/repair/$b/net_strokes.json" || fail "net_strokes.py $b failed"
  same "$b/net_strokes.json"
  python3 "$here/tools/place.py" "$here/$b" "$work/$b.kicad_sch" > "$work/repair/$b/01-place.json" || fail "place.py $b failed"
  same "$b/01-place.json"
  apply "$b.kicad_sch" "$b/01-place.json"
  python3 "$here/tools/pins.py" "$work/$b.kicad_sch" > "$work/repair/$b/pins.json" || fail "pins.py $b failed"
  same "$b/pins.json"
  python3 "$here/$b/02-wire.py" "$work/repair/$b/pins.json" "$work/repair/$b/ports.json" "$b.kicad_sch" \
    "$work/repair/$b/02-wire.nets.json" > "$work/repair/$b/02-wire.json" || fail "02-wire.py $b failed"
  same "$b/02-wire.json"
  same "$b/02-wire.nets.json"
  apply "$b.kicad_sch" "$b/02-wire.json"
  if [ -f "$here/$b/03-pwr-flags.py" ]; then
    python3 "$here/$b/03-pwr-flags.py" "$work/repair/$b/pins.json" "$b.kicad_sch" > "$work/repair/$b/03-pwr-flags.json" \
      || fail "03-pwr-flags.py $b failed"
    same "$b/03-pwr-flags.json"
    apply "$b.kicad_sch" "$b/03-pwr-flags.json"
  fi
  (cd "$root" && bun tools/draught/hierarchical-labels.ts ops "$module" "$b" "$work/$b.kicad_sch") \
    > "$work/repair/$b/04-hierarchical-labels.json" || fail "hierarchical-labels.ts ops $b failed"
  same "$b/04-hierarchical-labels.json"
  apply "$b.kicad_sch" "$b/04-hierarchical-labels.json"
  (cd "$root" && bun tools/draught/hierarchical-labels.ts check "$module" "$b" "$work/$b.kicad_sch") \
    || fail "block $b fails the hierarchical-label post-condition after its op-list"
  python3 "$here/tools/text_edits.py" "$here/$b" "$work/$b.kicad_sch" "$work/repair/$b/02-wire.nets.json" \
    "$work/repair/$b/net_strokes.json" || fail "text_edits.py $b failed"
  check "$b.kicad_sch" "01 to 05" "$want"
  cmp -s "$work/$b.kicad_sch" "$drafted/$b.kicad_sch" || fail "the replayed $b.kicad_sch differs from the committed $drafted/$b.kicad_sch"
  echo "the replayed $b.kicad_sch is byte-identical to the committed sheet"
}
repair_block interface "$PAGE_INTERFACE"
repair_block clock "$PAGE_CLOCK"
repair_block reset_boot "$PAGE_RESET_BOOT"
repair_block swd "$PAGE_SWD"
repair_block usb_dfu "$PAGE_USB_DFU"
repair_block id_strap "$PAGE_ID_STRAP"
repair_block qspi "$PAGE_QSPI"
# Task 7c: the same steps for vdda, sdram and decoupling.
repair_block vdda "$PAGE_VDDA"
repair_block sdram "$PAGE_SDRAM"
repair_block decoupling "$PAGE_DECOUPLING"
# Task 7d: the same steps for mcu.
repair_block mcu "$PAGE_MCU"

# 3. The committed sym-lib-table names the project symbol library IN PLACE in the repository (one
#    copy of each symbol), where a draft's names a copy in its own directory (TOOLING.md C4). Make
#    it here and require it byte-identical to the committed one, and the library it names to exist.
lib_rel="../../../circuits/h7-platform/h7-platform.kicad_sym"
[ -f "$drafted/$lib_rel" ] || fail "the committed sym-lib-table names $lib_rel, which does not exist from the page's directory"
printf '(sym_lib_table\n%s(version 7)\n%s(lib (name "h7-platform")(type "KiCad")(uri "${KIPRJMOD}/%s")(options "")(descr "project library, circuits/h7-platform/h7-platform.kicad_sym"))\n)\n' \
  "$(printf '\t')" "$(printf '\t')" "$lib_rel" > "$work/sym-lib-table" || fail "could not write the sym-lib-table"
cmp -s "$work/sym-lib-table" "$drafted/sym-lib-table" || fail "the sym-lib-table this replay makes differs from the committed one"
echo "the committed sym-lib-table matches the one this replay makes"

# 4. The root (Task 7e): assemble-root.ts's starting text and op-list (its arrangement fits US Letter
#    since Task 7e fix round 1, ruling CR-MODULE-ROOT-FITS-LETTER), the root-held PWR_FLAGs
#    (root-flags.ts, ruling CR-MODULE-PWR-FLAGS), their references renamed #FLG0<n> (root_flag_refs.py),
#    every sheet pin's name justified into its box (root_pin_justify.py; akcli writes no justify),
#    and the .kicad_pro with its one ERC exclusion (kicad-pro.ts, ruling CR-MODULE-VCAP-ERC). Every
#    block sheet must be unchanged by it.
mkdir -p "$work/repair/root"
(cd "$root" && bun tools/draught/assemble-root.ts blank "$board") > "$work/$board.kicad_sch" || fail "assemble-root.ts blank failed"
check "$board.kicad_sch" "assemble-root blank" "$ROOT_BLANK"
(cd "$root" && bun tools/draught/assemble-root.ts ops "$module" h7Module "$board") > "$work/repair/root/01-assemble.json" \
  || fail "assemble-root.ts ops failed"
same root/01-assemble.json
apply "$board.kicad_sch" root/01-assemble.json
(cd "$root" && bun "$here/tools/root-flags.ts" "$board") > "$work/repair/root/02-pwr-flags.json" || fail "root-flags.ts failed"
same root/02-pwr-flags.json
apply "$board.kicad_sch" root/02-pwr-flags.json
python3 "$here/tools/root_flag_refs.py" "$work/$board.kicad_sch" 3 || fail "root_flag_refs.py failed"
python3 "$here/tools/root_pin_justify.py" "$work/$board.kicad_sch" "$work/repair/root/01-assemble.json" || fail "root_pin_justify.py failed"
check "$board.kicad_sch" "root, blank to step 5" "$ROOT"
cmp -s "$work/$board.kicad_sch" "$drafted/$board.kicad_sch" || fail "the replayed $board.kicad_sch differs from the committed $drafted/$board.kicad_sch"
echo "the replayed $board.kicad_sch is byte-identical to the committed root"
(cd "$root" && bun "$here/tools/kicad-pro.ts" "$work" "$board") > "$work/$board.kicad_pro" || fail "kicad-pro.ts failed"
check "$board.kicad_pro" "kicad-pro.ts" "$ROOT_PRO"
cmp -s "$work/$board.kicad_pro" "$drafted/$board.kicad_pro" || fail "the replayed $board.kicad_pro differs from the committed one"
echo "the replayed $board.kicad_pro is byte-identical to the committed one"
for b in $BLOCKS; do
  cmp -s "$work/$b.kicad_sch" "$drafted/$b.kicad_sch" || fail "after the root, $b.kicad_sch differs from the committed sheet"
done
echo "every block sheet is unchanged by the root's assembly"
