import { describe, expect, it } from "bun:test"
import { buildGuideHtml, type GuideInput, type GuideSchematic } from "../../tools/guide/guide.ts"
import { SCHEMATIC_PAGE } from "../../tools/guide/merge-pdf.ts"
import { GUIDE_PAPER } from "../../tools/guide/paper.ts"

const input = (schematic: GuideSchematic): GuideInput => ({
  boardName: "pultec-low-boost",
  generated: "2026-10-27",
  layoutPath: "boards/pultec-low-boost/pultec-low-boost.perfboard.vrt",
  schematic,
  images: { designators: "<svg/>", values: "<svg/>", copper: "<svg/>", clusters: undefined },
  checklist: [],
  powerUpChecks: undefined,
  wiringPath: undefined,
  scaffold: undefined,
  // Tracks `schematic`, because `buildGuideHtml` refuses a packet that claims
  // a schematic page without knowing its size, and one that knows a size for
  // a page it does not carry.
  schematicPaper:
    schematic.kind === "printed" || schematic.kind === "generated" ? GUIDE_PAPER : undefined,
})

/**
 * **THE `drawn: true` FIXTURES BELOW CARRIED A FALLBACK-FIELD-PLACEMENT REASON UNTIL 2026-10-30,
 * AND NO SUCH REASON CAN REACH THIS FUNCTION ANY MORE.** `tools/guide/schematic-source.ts` withheld
 * a page whose sheets carried any `fieldFallbacks`; the owner struck that - *"STOP PASSING
 * JUDGEMENT ON LAYOUT!!! ... YOU MUST SHOW ME WHAT YOU THINK MIGHT BE WRONG!!!"* - and
 * `lib/schgen/findings.ts` classes a `field-fallback` `usable`, so a crowded sheet now PRINTS.
 *
 * The expectations are MOVED rather than deleted: what `buildGuideHtml` must do with a `"withheld"`
 * input is unchanged and still worth holding, so the same assertions run against the reason a
 * `drawn: true` withholding can actually carry now - a `defective` class, the one ground
 * `EVALUATING-DRAWINGS.md` §3 permits. A fixture carrying a reason the resolver cannot produce
 * would be a test passing on a situation that no longer exists.
 */
const DEFECTIVE_REASON =
  "defective: the drawing is UNRATIFIED (defective): 1 finding(s) over 1 sheet(s). " +
  "[short] sheet main: wire 3 of input_stage crosses net HI_BOOST_OUT without a junction"

describe("a withheld schematic is a different claim from an absent one", () => {
  it("names the reason, so nobody reads a withheld sheet as a board with no schematic", () => {
    const html = buildGuideHtml(
      input({
        kind: "withheld",
        declarationPath: "boards/pultec-low-boost/perfboard.json",
        circuitPath: "circuits/pultec/physical/low-boost.ts",
        reason: DEFECTIVE_REASON,
        drawn: true,
      }),
    )
    expect(html).toContain("crosses net HI_BOOST_OUT without a junction")
    expect(html).toContain("withheld")
    expect(html).not.toContain("there is no schematic for pultec-low-boost to print")
  })

  it("a generated-and-clean schematic prints as a page, like a hand-authored one, and says so", () => {
    const html = buildGuideHtml(input({ kind: "generated" }))
    // THE PAGE IN THIS DOCUMENT, not a second file's name. This assertion read
    // `toContain("schematic.pdf")` until 2026-10-30, when the schematic became
    // a page of the one document and that second file stopped existing - so
    // the string it checked for would have passed on a packet naming a file
    // that is not there.
    expect(html).toContain(`page ${String(SCHEMATIC_PAGE)} of this document`)
    expect(html).not.toContain("schematic.pdf")
    expect(html).not.toContain("withheld")
    // THE LINE THAT DISTINGUISHES A schgen-DRAWN SHEET FROM A HAND-AUTHORED ONE - the only thing on
    // this page that says the schematic is generated rather than hand-drawn, so a test that never
    // asserts it would pass just as well on a page that dropped the note silently.
    expect(html).toContain("generated by <code>schgen</code>")
    expect(html).toContain("not hand-drawn")
  })

  it("an absent schematic still prints the no-schematic notice, unchanged", () => {
    const html = buildGuideHtml(
      input({
        kind: "none",
        declarationPath: "boards/pultec-low-boost/perfboard.json",
        circuitPath: "circuits/pultec/physical/low-boost.ts",
      }),
    )
    // NOT "no schematic" - that phrase also appears in the withheld notice ("this packet prints no
    // schematic for ..."), so it would pass on a withheld page too. The heading is unique to this
    // notice.
    expect(html).toContain("No schematic in this packet")
    expect(html).not.toContain("Schematic withheld")
  })

  it("a withheld-but-nothing-drawn result does not claim a sheet was generated", () => {
    // THE LIVE DEFECT THIS BRANCH GUARDS: `outcome === \"refused\"` and the zero-sheets case both
    // drew nothing, and the notice must not say schgen "generated one ... and it was withheld" -
    // that is the drawn:true claim, and printing it here would assert a drawing exists when none
    // does.
    const html = buildGuideHtml(
      input({
        kind: "withheld",
        declarationPath: "boards/pultec-mid/perfboard.json",
        circuitPath: "circuits/pultec/physical/mid.ts",
        reason: "circuit is invalid: part SW_MID: pin 12 is neither on a net nor declared not connected",
        drawn: false,
      }),
    )
    expect(html).toContain("withheld")
    expect(html).toContain("produced no sheet to judge")
    expect(html).not.toContain("schgen generated one from this board's own declaration and it was withheld")
  })

  it("a withheld-and-drawn result claims a sheet was generated and withheld for what is on it", () => {
    const html = buildGuideHtml(
      input({
        kind: "withheld",
        declarationPath: "boards/pultec-low-boost/perfboard.json",
        circuitPath: "circuits/pultec/physical/low-boost.ts",
        reason: DEFECTIVE_REASON,
        drawn: true,
      }),
    )
    expect(html).toContain("schgen generated one from this board's own declaration and it was withheld")
    expect(html).not.toContain("produced no sheet to judge")
  })
})
